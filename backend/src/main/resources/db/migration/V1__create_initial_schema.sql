CREATE TABLE news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    subtitle VARCHAR(300),
    slug VARCHAR(180) NOT NULL,
    content TEXT NOT NULL,
    image_url VARCHAR(2048),
    author_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,
    CONSTRAINT uk_news_slug UNIQUE (slug),
    CONSTRAINT fk_news_author FOREIGN KEY (author_id) REFERENCES app_users (id),
    CONSTRAINT fk_news_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_news_status CHECK (status IN ('DRAFT', 'PUBLISHED'))
);

CREATE INDEX idx_news_published_at ON news (published_at DESC)
    WHERE status = 'PUBLISHED' AND published_at IS NOT NULL;
CREATE INDEX idx_news_author_id ON news (author_id);
CREATE INDEX idx_news_category_id ON news (category_id);
